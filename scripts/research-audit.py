#!/usr/bin/env python3
"""Audit profile evidence and generate the per-person editorial coverage ledger.

This checks structure and provenance, not historical truth. Human source reading
and editorial review remain necessary even when every structural check passes.
"""
import argparse
import json
import re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--strict', action='store_true', help='Require every person to have a reviewed narrative')
args = parser.parse_args()
data = json.loads((ROOT / 'data/popes.json').read_text())
sources = {source['id']: source for source in data['sources']}
errors, rows = [], []


def words(text):
    return len(re.findall(r"\b[\w’'-]+\b", text))


def check_passage(person, field, value):
    if not value.get('text', '').strip():
        errors.append(f'{person["name"]}: empty {field}')
    refs = value.get('sourceRefs', [])
    if not refs or any(ref not in sources for ref in refs):
        errors.append(f'{person["name"]}: missing or invalid passage references for {field}')


for person in data['people']:
    narrative = person.get('narrative')
    total = words(' '.join([person['summary'], person['biography'], person['context'], *[action['text'] for action in person['actions']]]))
    if not narrative:
        rows.append((person, 'Pending', total, 0, 'Not individually reviewed'))
        if args.strict:
            errors.append(f'{person["name"]}: no individual narrative review')
        continue
    review = narrative['review']
    check_passage(person, 'introduction', narrative['summary'])
    for field in ['biography', 'context']:
        passages = narrative[field]['paragraphs']
        if not passages:
            errors.append(f'{person["name"]}: missing {field}')
        for index, passage in enumerate(passages):
            check_passage(person, f'{field} paragraph {index + 1}', passage)
    if not person['actions']:
        errors.append(f'{person["name"]}: no actions or evidence assessment')
    for index, action in enumerate(person['actions']):
        check_passage(person, f'action {index + 1}', action)
    for field in ['birthDate', 'saintStatus', 'antipopeReview']:
        refs = narrative[field].get('sourceRefs', [])
        if not refs or any(ref not in sources for ref in refs):
            errors.append(f'{person["name"]}: {field} has no checked evidence')
    for ref in review['sourcesRead']:
        source = sources.get(ref, {})
        verified = source.get('access', {}).get('verified') or any(reading.get('access', {}).get('verified') for reading in source.get('researchReadings', []))
        if not verified or not source.get('passage'):
            errors.append(f'{person["name"]}: source {ref} lacks verified reading or supporting passage')
    if not set(['biography', 'actions', 'context', 'birthDate', 'recognition', 'claimants']).issubset(review['fieldsChecked']):
        errors.append(f'{person["name"]}: incomplete field review')
    if re.search(r'appears at position|Vatican roster records his origin', person['summary']):
        errors.append(f'{person["name"]}: roster placeholder remains')
    prose=' '.join([person['summary'],person['biography'],person['context'],person['saintStatus'].get('recognition',''),*[action['text'] for action in person['actions']]])
    if re.search(r'\b(?:in|In|of|The|the|on|On|by|from|after|before)\d', prose):
        errors.append(f'{person["name"]}: missing word/date spacing')
    if re.search(r'\b[a-z]{2,}[A-Z][a-z]+\b', prose):
        errors.append(f'{person["name"]}: joined words in public prose')
    claimant_review = narrative['antipopeReview']
    if claimant_review['status'] == 'reviewed-linked' and 'identifies no competing papal claimant' in claimant_review['note']:
        errors.append(f'{person["name"]}: claimant review contradicts its linked rivals')
    for candidate in data['people']:
        if ' ' in candidate['name'] and re.search(r'\b'+re.escape(candidate['name'].replace(' ',''))+r'\b',prose):
            errors.append(f'{person["name"]}: missing name spacing for {candidate["name"]}')
            break
    issues = review.get('openIssues', [])
    status = 'Scarce evidence reviewed' if review['coverage'] == 'scarce-evidence' else 'Sourced profile'
    rows.append((person, status, total, len(review['sourcesRead']), '; '.join(issues) or 'See individual research notes'))

for claimant in data['antipopes']:
    for field in ['summary','biography']:
        if not claimant.get(field) or not claimant.get('claims',{}).get(field):
            errors.append(f'{claimant["name"]}: missing {field} evidence')

counts = Counter(status for _, status, _, _, _ in rows)
lines = [
    '# Individual profile research ledger', '',
    'Generated by `python3 scripts/research-audit.py --strict` from the shared dataset. Structural coverage is distinct from final historical/editorial verification. Numbered references and paragraph evidence are in each person’s `narrative` record.', '',
    f'{len(rows)} people, {len(data["pontificates"])} pontificate entries. ' + '; '.join(f'{status}: {count}' for status, count in counts.items()) + '.', '',
    '| First Vatican position | Person | Narrative coverage | Narrative words | Sources read | Editorial notes |',
    '| --- | --- | --- | ---: | ---: | --- |',
]
for person, status, total, count, issues in rows:
    safe_issues = issues.replace('|', '\\|').replace('\n', ' ')
    lines.append(f'| {person["firstOrder"]} | {person["name"]} | {status} | {total} | {count} | {safe_issues} |')
lines += ['', 'Unknown birth dates may be the correct result of individual research. A missing positive saint designation does not establish non-sainthood. Evidence-limited profiles explain what survives and assess later traditions. Portrait sourcing is separate from narrative completeness.', '']
(ROOT / 'docs/internal/research-coverage.md').write_text('\n'.join(lines))
print(json.dumps({'people':len(rows), 'coverage':dict(counts), 'sources':len(sources), 'errors':errors}, ensure_ascii=False, indent=2))
raise SystemExit(bool(errors))
